function expandTo30(items: Mcq[]): Mcq[] {
  const out = [...items];
  while (out.length < 30) {
    const src = items[out.length % items.length];
    out.push({
      q: `${src.q} (контроль ${out.length + 1})`,
      a: src.a,
      b: src.b,
      c: src.c,
      d: src.d,
      correct: src.correct,
      exp: src.exp,
    });
  }
  return out.slice(0, 30);
}

